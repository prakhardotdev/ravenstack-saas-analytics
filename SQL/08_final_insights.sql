-- ============================================
-- Phase 8: Business Insights & Recommendations
-- RavenStack SaaS Churn Analysis
-- ============================================

-- INSIGHT 1: Revenue Concentration
-- Enterprise plan = 30.8% of accounts but generates 83% of total MRR ($8.47M)
-- Recommendation: Prioritize Enterprise customer success and retention above all else

-- INSIGHT 2: Churn Rate is Uniform Across All Plans
-- Basic: 22.02% | Pro: 21.91% | Enterprise: 22.08%
-- Recommendation: Plan tier is NOT the driver of churn
-- Investigate product and support experience instead

-- INSIGHT 3: Features is the #1 Churn Reason (19%)
-- Features > Support > Budget > Unknown > Competitor > Pricing
-- Recommendation: Conduct feature gap analysis
-- Prioritize missing features in product roadmap

-- INSIGHT 4: DevTools Industry Has Highest Churn (30.97%)
-- Cybersecurity is the most loyal segment (16%)
-- Recommendation: Run feedback sessions with DevTools customers
-- Invest more in growing the Cybersecurity segment

-- INSIGHT 5: Referral Source Impacts Retention
-- Event referral = 30.21% churn (highest)
-- Partner referral = 14.61% churn (lowest)
-- Recommendation: Expand partner referral program
-- Add structured onboarding for event-sourced customers

-- INSIGHT 6: Churn is Growing Month Over Month
-- Early 2023: 1-5 churns per month
-- Late 2024: 25-35 churns per month
-- Recommendation: Launch an immediate customer retention program
-- Set up churn early warning system

-- INSIGHT 7: Significant Revenue Lost to Churn
-- $1,179,139 MRR lost from churned subscriptions
-- Recommendation: A 5% churn reduction saves approximately $59,000 MRR monthly

-- INSIGHT 8: Downgrade is a Leading Churn Indicator
-- 8.83% of churned customers had a preceding downgrade
-- Recommendation: When a customer downgrades, trigger immediate
-- outreach from the customer success team

-- INSIGHT 9: Upgrade Does Not Guarantee Retention
-- 20.5% of churned customers had a preceding upgrade
-- Recommendation: Improve post-upgrade onboarding
-- Ensure customers extract value after plan upgrades

-- INSIGHT 10: Reactivation Opportunity Exists
-- 61 customers (10.2%) reactivated after churning
-- Recommendation: Launch a structured win-back campaign
-- Offer targeted incentives to recently churned customers
